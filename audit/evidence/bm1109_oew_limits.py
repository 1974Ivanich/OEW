"""Проверка чисел приложения v2 к аудиту BM1109 (напряжение OEW, dead time, ZSC, энергетика).

Печатает ровно те величины, которые попали в документ:
  - четыре коэффициента OEW/звезда по режимам модуляции;
  - долю 2/sqrt(3) от шестиступенчатого предела;
  - ошибку dead time: один мост / дифференциальная OEW / нулевая последовательность;
  - спектр нулевой последовательности от dead time (3-я гармоника);
  - медь, инвертор и ZSC-выигрыш: сценарий 7,5 Ом (другой мотор) и допущение 0,075..0,30 Ом.

15 Ом / 7,5 Ом к BM1109 не относятся (docs/BM1109_CONFIG_PASSPORT.md §3.1).
"""
import math

print("=== 1. Коэффициенты OEW / звезда (амплитуда основной гармоники фазы) ===")
print(f"  линейный SVPWM : {1.0 / (1.0 / math.sqrt(3)):.4f}")
print(f"  шестиступенчатый: {(4 / math.pi) / (2 / math.pi):.4f}")
print(f"  текущий код (звезда без инжекции Vdc/2, OEW VM 0,90): {0.90 / 0.5:.3f}")
print(f"  звезда с SVPWM против OEW VM 0,90: {0.90 * math.sqrt(3):.3f}")
print(f"  2/sqrt(3) = {2 / math.sqrt(3):.4f} Vdc = {(2 / math.sqrt(3)) / (4 / math.pi) * 100:.1f}% шестиступенчатого предела")

print("\n=== 2. Dead time: Vdc=40 В, t_d=1.5 мкс, f_sw=5 кГц ===")
td, Tsw, Vdc = 1.5e-6, 200e-6, 40.0
k = td / Tsw * Vdc
print(f"  k = (t_d/T_sw)*Vdc = {k:.3f} В (один мост)")
print(f"  дифференциальная ошибка обмотки OEW = 2k = {2 * k:.2f} В")
print(f"  нулевая последовательность = (2/3)k = {2 / 3 * k:.3f} В")

N = 7200
s = [math.copysign(1.0, math.sin(2 * math.pi * i / N))
     + math.copysign(1.0, math.sin(2 * math.pi * i / N - 2 * math.pi / 3))
     + math.copysign(1.0, math.sin(2 * math.pi * i / N - 4 * math.pi / 3)) for i in range(N)]


def amp(n):
    c = sum(s[i] * math.cos(2 * math.pi * n * i / N) for i in range(N)) * 2 / N
    sn = sum(s[i] * math.sin(2 * math.pi * n * i / N) for i in range(N)) * 2 / N
    return math.hypot(c, sn)


print(f"  сумма знаков трёх фаз принимает только {sorted(set(round(v) for v in s))}"
      " -> период 120°, т.е. 3-я гармоника основной")
print(f"  амплитуда 3-й гармоники суммы знаков: {amp(3):.4f} (= 4/pi)")
print(f"  => 3-я гармоника напряжения u0: {amp(3) * 2 / 3 * k:.3f} В "
      f"(проверка: (4/pi)*(2/3)k = {4 / math.pi * 2 / 3 * k:.3f} В)")
print(f"  амплитуда 9-й гармоники u0: {amp(9) * 2 / 3 * k:.3f} В (для O3 — следующий по величине член)")

print("\n=== 3. Энергетика: СЦЕНАРИЙ R_LL=15 Ом (другой мотор), звезда, I_peak=2 А ===")
print("  внимание: 15 Ом / 7,5 Ом к BM1109 не относятся (паспорт §3.1), блок сценарный")
Rph, Ip = 7.5, 2.0
Pcu = 1.5 * Ip ** 2 * Rph
Pinv = 1.75 * 3 * (2 / math.pi) * Ip          # V_CE(sat)*sum|i|, два прибора на путь
Pzsc = 0.1225 * Pcu                            # 12,25 % при E3/E1 = 0,35
print(f"  медь 3*I_rms^2*R_ph = {Pcu:.1f} Вт")
print(f"  добавка второго инвертора (оценка, V_CE=1,75 В) = {Pinv:.1f} Вт")
print(f"  выигрыш от ZSC при E3/E1=0,35 = {Pzsc:.1f} Вт  -> баланс {Pzsc - Pinv:+.1f} Вт")
for r in (0.10, 0.20):
    print(f"  для сравнения E3/E1={r}: выигрыш {r * r * Pcu:.1f} Вт -> баланс {r * r * Pcu - Pinv:+.1f} Вт")
print("  --- то же для 48-В машины: допущение R_ph=0,075..0,30 Ом (паспорт §3.1) ---")
for Rlo in (0.075, 0.15, 0.30):
    Pcu_lo = 1.5 * Ip ** 2 * Rlo
    gain_lo = 0.1225 * Pcu_lo
    print(f"  R_ph={Rlo:.3f} Ом: медь {Pcu_lo:.2f} Вт, выигрыш ZSC {gain_lo:.2f} Вт "
          f"({gain_lo / 96 * 100:.2f} % от P_DC) -> баланс {gain_lo - Pinv:+.1f} Вт")

print("\n=== 4. Модель напряжения прошивки (src/foc.c:1135,1140) ===")
print("  два моста: V_phase = (2d-1)*Vdc = mod*Vdc")
print("  один мост (звезда): V_phase = mod*Vdc/2 -> модель завышает в 2 раза")
