#ifndef BM1109_CONFIG_H
#define BM1109_CONFIG_H

/* ============================================================================
 *  BM1109 — конфигурация измерительной прошивки R и L.
 *
 *  Область действия: ТОЛЬКО ветка feature/bm1109-rl-measurement.
 *  OEW-прошивка (../main.c и ../src/*) этот файл не включает и не меняется.
 *
 *  Числа ниже взяты из фактической разводки этой ветки:
 *    - src/pwm_board_pins.h — карта выводов и SD-линий;
 *    - src/pwm.c            — 170 МГц / PSC=16 / ARR=999 / dead time 1500 нс;
 *    - src/adc.c / adc.h    — каналы, делитель 1:125, 40,32 мВ/А на PA0.
 *  Ничего «по памяти из другого стенда» здесь нет: в master-ветке карта
 *  выводов и тактирование другие, и переносить их сюда нельзя.
 * ========================================================================== */

#define BM1109_CFG_VERSION      "bm1109-rl-1"

/* ---------------------------------------------------------------------------
 *  1. Тактирование и UART
 *  Как в main.c этой ветки: HSI16 → PLL M=4, N=85, R=2 → 170 МГц.
 * ------------------------------------------------------------------------- */
#define BM1109_SYSCLK_HZ        170000000UL
#define BM1109_UART_BAUD        115200U

/* ---------------------------------------------------------------------------
 *  2. Силовой мост
 *
 *  Плата несёт ДВА моста (TIM1 и TIM8). BM1109 — звезда с тремя выводами,
 *  поэтому измерение идёт через два плеча ОДНОГО моста; второй мост держится
 *  полностью выключенным.
 *
 *  BM1109_PWM_TIM_INSTANCE: 1 = TIM1, 2 = TIM8 — к какому мосту подключён
 *  разъём BM1109. ПРОВЕРИТЬ по схеме (G8 паспорта конфигурации).
 *  При неверном выборе измерение безопасно (тока нет), но недействительно:
 *  прошивка сообщит «нет тока».
 * ------------------------------------------------------------------------- */
#define BM1109_PWM_TIM_INSTANCE 1

#if BM1109_PWM_TIM_INSTANCE == 1
  #define BM1109_PWM_TIM         TIM1
  #define BM1109_PWM_TIM_RCC     RCC_APB2ENR_TIM1EN
#elif BM1109_PWM_TIM_INSTANCE == 2
  #define BM1109_PWM_TIM         TIM8
  #define BM1109_PWM_TIM_RCC     RCC_APB2ENR_TIM8EN
#else
  #error "BM1109_PWM_TIM_INSTANCE: допустимо 1 (TIM1) или 2 (TIM8)"
#endif

#define BM1109_PWM_PSC          16U      /* 170 МГц / 17 = 10 МГц счёт */
#define BM1109_PWM_ARR          999U     /* 10 МГц / (2*1000) = 5 кГц center-aligned */
#define BM1109_PWM_DTG          0xC0U    /* encode(1500 нс при 170 МГц), как в pwm.c */
#define BM1109_PWM_FREQ_HZ      (BM1109_SYSCLK_HZ / (BM1109_PWM_PSC + 1U) / (2U * (BM1109_PWM_ARR + 1U)))

/* Максимальная командная скважность (1/65536 периода). Реальную защиту даёт
 * контроль тока; потолок нужен, чтобы цикл подстройки не ушёл в разнос. */
#define BM1109_DUTY_MAX_Q16     16384U  /* 25 % */

/* ---------------------------------------------------------------------------
 *  3. Датчики (фактическая разводка этой ветки)
 *
 *  Ток: PA0 = ADC1_IN1, цепь DC-шунта, 40,32 мВ/А (adc.h:
 *  ADC_DC_SHUNT1_UV_PER_A = 63000*64/100). Не «шунт 30 мОм» из master —
 *  здесь задаётся сразу крутизна канала, включая делитель перед АЦП.
 *  Vbus: PC4 = ADC2_IN5, делитель 1:125.
 * ------------------------------------------------------------------------- */
#define BM1109_ADC_VREF_MV      3300L
#define BM1109_ADC_MAX_CODE     4095L
#define BM1109_ADC_UV_PER_A     40320L  /* мкВ на 1 А на входе PA0 */
#define BM1109_VBUS_DIVIDER     125L
#define BM1109_ADC_CH_CURRENT   1U      /* ADC1_IN1 = PA0 */
#define BM1109_ADC_CH_VBUS      5U      /* ADC2_IN5 = PC4 */
#define BM1109_ADC_AVG_SAMPLES  64U

/* ---------------------------------------------------------------------------
 *  4. Ограничения безопасности (только BM1109)
 * ------------------------------------------------------------------------- */
#define BM1109_VBUS_MIN_MV      5000L
#define BM1109_VBUS_MAX_MV      60000L
#define BM1109_I_PEAK_MA        2500L   /* немедленное отключение */
#define BM1109_I_TARGET_MA      800L
#define BM1109_R_MAX_ON_MS      150U    /* бюджет включения на одну точку R */
#define BM1109_L_MAX_PULSE_US   300U
#define BM1109_ABS_MAX_ON_US    250000U
#define BM1109_DISCHARGE_MS     20U

/* ---------------------------------------------------------------------------
 *  5. Метод R: три точки по току, МНК по U = R*I + U0.
 *
 *  U0 собирает постоянные падения на ключах, потерю на dead time и сдвиг
 *  токового канала. Поэтому R — наклон, а не U/I: на R порядка 0,1 Ом
 *  падение на ключах сравнимо с падением на обмотке.
 * ------------------------------------------------------------------------- */
#define BM1109_R_POINT_COUNT    3U
#define BM1109_R_TARGET_PERMILLE {500U, 1000U, 1500U}   /* 400/800/1200 мА */
#define BM1109_R_INIT_DUTY_Q16  164U    /* 0,25 % периода */
#define BM1109_R_TOL_PCT        5U
#define BM1109_R_SETTLE_PERIODS 150U    /* 30 мс при 5 кГц */
#define BM1109_R_MAX_ITER       600U    /* до 120 мс на точку */

/* ---------------------------------------------------------------------------
 *  6. Метод L: импульс постоянного напряжения, три выборки тока.
 *
 *  di/dt = U/L: при 6 В и 50 мкГн это 120 А/мс (2 А за ~17 мкс). Поэтому
 *  импульс разрешён только при пониженном Vbus, а моменты выборок
 *  автомасштабируются (x2 до 8 раз), пока прирост тока не станет измеримым.
 * ------------------------------------------------------------------------- */
#define BM1109_L_MAX_VBUS_MV    6000L
#define BM1109_L_T_US           {6U, 14U, 30U}
#define BM1109_L_T_SCALE_MAX    3U
#define BM1109_L_MIN_DELTA_MA   50L
#define BM1109_L_SWITCH_DROP_MV 0L      /* падение на двух ключах; 0 = не учитывать */

/* --- проверки согласованности (ловим опечатки при сборке) --- */
#if BM1109_I_TARGET_MA >= BM1109_I_PEAK_MA
#error "BM1109_I_TARGET_MA должен быть меньше BM1109_I_PEAK_MA"
#endif
#if BM1109_L_MAX_VBUS_MV > BM1109_VBUS_MAX_MV
#error "BM1109_L_MAX_VBUS_MV должен быть <= BM1109_VBUS_MAX_MV"
#endif
#if BM1109_VBUS_MIN_MV >= BM1109_VBUS_MAX_MV
#error "BM1109_VBUS_MIN_MV должен быть меньше BM1109_VBUS_MAX_MV"
#endif
#if (BM1109_PWM_ARR + 1U) > 65535U
#error "BM1109_PWM_ARR вне диапазона 16-битного CCR"
#endif

#endif /* BM1109_CONFIG_H */
